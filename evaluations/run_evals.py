#!/usr/bin/env python3
"""Evaluation harness.

What this script does (implemented):
  - validates the regression dataset and golden task files (shape, skill and workflow references)
  - optionally checks a captured project workspace against a golden task's expected evidence paths
  - writes a benchmark report skeleton in which every model-dependent score is NOT_RUN until a rater fills it

What this script does not do: run a model, score transcripts, or invent results.

Usage:
  python evaluations/run_evals.py --check
  python evaluations/run_evals.py --report evaluations/benchmark-reports/2026-11-20-kiro-ide.md --host "Kiro IDE 1.4" --model "<model id>"
  python evaluations/run_evals.py --golden C --workspace /path/to/project --report out.md
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts" / "validate"))
from common import Report, load_yaml  # noqa: E402

DATASET = ROOT / "evaluations/datasets/regression-cases.json"
GOLDEN_DIR = ROOT / "evaluations/golden-tasks"


def check_assets() -> Report:
    import validate_evaluations
    return validate_evaluations.run()


def golden_tasks() -> dict[str, dict]:
    out = {}
    for p in sorted(GOLDEN_DIR.glob("*.yaml")):
        data = load_yaml(p, Report("golden"))
        if isinstance(data, dict):
            out[str(data.get("id"))] = data
    return out


def check_workspace(task: dict, workspace: Path) -> list[tuple[str, str, str]]:
    """Return (path, status, note) for each expected evidence item. Presence only; content is for raters."""
    rows = []
    for item in task.get("expected_evidence", []):
        rel = item["path"]
        if rel == "repository":
            rows.append((rel, "MANUAL", "repository checks are performed by raters"))
            continue
        p = workspace / rel
        if p.exists():
            rows.append((rel, "PRESENT", "content to be scored by raters"))
        else:
            rows.append((rel, "MISSING", ""))
    return rows


def write_report(path: Path, host: str, model: str, golden: dict | None, workspace_rows: list | None) -> None:
    ds = json.loads(DATASET.read_text(encoding="utf-8"))
    now = datetime.now(timezone.utc).isoformat()
    lines = [f"# Benchmark report — {now[:10]} — {host} — {model}", "",
             f"Generated by `evaluations/run_evals.py` at {now}. Every score below is `NOT_RUN` until a rater replaces it with a value and cites evidence. Do not publish a report with NOT_RUN rows described as results.", "",
             "## Environment", "", f"- Host: {host}", f"- Model: {model}", "- Skills version: " + (ROOT / "VERSION").read_text(encoding="utf-8").strip(),
             "- Raters: <names/roles; must not include the model that produced the work>", "", "## Regression cases", "",
             "| Case | Expected behaviour (0-3) | Forbidden avoided (0-3) | Honesty (0-3) | Specificity (0-3) | Approval respected (0-3) | Evidence (transcript path) |",
             "|---|---|---|---|---|---|---|"]
    for c in ds["cases"]:
        lines.append(f"| {c['id']} | NOT_RUN | NOT_RUN | NOT_RUN | NOT_RUN | NOT_RUN | |")
    lines += ["", "## Golden task", ""]
    if golden:
        lines += [f"Task {golden['id']}: {golden['name']} (workflow `{golden['workflow']}`)", "",
                  "| Expected evidence | Presence | Rubric scores (per dimension) | Evidence cited |", "|---|---|---|---|"]
        if workspace_rows:
            for rel, status, note in workspace_rows:
                lines.append(f"| `{rel}` | {status} | NOT_RUN | {note} |")
        else:
            for item in golden.get("expected_evidence", []):
                lines.append(f"| `{item['path']}` | NOT_RUN | NOT_RUN | |")
        lines += ["", "### Forbidden behaviours observed", ""] + [f"- [ ] {f}" for f in golden.get("forbidden", [])]
        lines += ["", "### Cost and time", "", "| Item | Value |", "|---|---|"] + [f"| {k} | NOT_MEASURED |" for k in golden.get("cost_and_time_recording", [])]
    else:
        lines.append("No golden task selected (use --golden A..E).")
    lines += ["", "## What could not be tested", "", "- <list>", "", "## Rater notes", "", "- <notes>", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Report skeleton written to {path}")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate evaluation assets and exit")
    ap.add_argument("--report", type=Path, help="write a report skeleton to this path")
    ap.add_argument("--host", default="<host>")
    ap.add_argument("--model", default="<model>")
    ap.add_argument("--golden", choices=["A", "B", "C", "D", "E"], help="golden task id")
    ap.add_argument("--workspace", type=Path, help="captured project workspace to check for expected evidence presence")
    args = ap.parse_args(argv)
    report = check_assets()
    report.print()
    if not report.ok:
        return 1
    if args.check and not args.report:
        return 0
    golden = golden_tasks().get(args.golden) if args.golden else None
    rows = check_workspace(golden, args.workspace) if (golden and args.workspace) else None
    if rows:
        for rel, status, note in rows:
            print(f"  {status:8} {rel}")
    if args.report:
        write_report(args.report, args.host, args.model, golden, rows)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
