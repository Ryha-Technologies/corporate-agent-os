#!/usr/bin/env python3
"""Render departments/*/roles.yaml into docs/organization/<department>.md plus an index, and render
workflows/*/workflow.yaml stage tables into workflows/<id>/STAGES.md."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "validate"))
from common import Report, load_all_agents, load_departments, load_yaml  # noqa: E402

OUT = ROOT / "docs" / "organization"
HEADER = "<!-- Generated by scripts/package/render_roles.py. Edit the YAML source, not this file. -->"
FIELDS = [
    ("mission", "Mission"), ("scope", "Scope of responsibility"), ("activities", "Core activities"),
    ("inputs", "Inputs"), ("outputs", "Outputs and deliverables"), ("decides", "Decisions it can make"),
    ("needs_approval", "Decisions requiring approval"), ("collaborates_with", "Collaborating roles"),
    ("reports_to", "Reporting relationship"), ("kpis", "KPIs"), ("quality", "Quality expectations"),
    ("tools", "Tools and resources"), ("failure_modes", "Common failure modes"),
    ("ai_autonomy", "Appropriate AI autonomy"), ("human_approval", "Human approval requirements"),
]


def _fmt(v) -> str:
    if isinstance(v, list):
        return "; ".join(str(x) for x in v)
    return str(v)


def render_department(data: dict) -> str:
    d = data["department"]
    lines = [f"# {d['name']}", "", HEADER, "", f"**Department id:** `{d['id']}`  ", f"**Mission:** {d['mission']}", "",
             "## Startup stage", "", d["startup_stage"], "", "## Agents operating in this department", "",
             ", ".join(f"`{a}`" for a in d.get("agents", [])) or "none", "", "## Roles", ""]
    for role in data.get("roles", []):
        lines.append(f"### {role['title']}")
        lines.append("")
        lines.append(f"Role id: `{role['id']}`")
        lines.append("")
        lines.append("| Field | Definition |")
        lines.append("|---|---|")
        for key, label in FIELDS:
            lines.append(f"| {label} | {_fmt(role.get(key, ''))} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def render_index(deps: dict[str, dict]) -> str:
    lines = ["# Organization directory", "", HEADER, "",
             "Every department with its mission, startup-stage guidance, agents and roles. Source of truth: `departments/<id>/roles.yaml`.", "",
             "| Department | Roles | Agents | Mission |", "|---|---|---|---|"]
    for did in sorted(deps):
        d = deps[did]["department"]
        lines.append(f"| [{d['name']}]({did}.md) | {len(deps[did].get('roles', []))} | {len(d.get('agents', []))} | {d['mission']} |")
    total_roles = sum(len(v.get("roles", [])) for v in deps.values())
    lines += ["", f"{len(deps)} departments, {total_roles} roles."]
    return "\n".join(lines) + "\n"


def render_stages(wf: dict) -> str:
    lines = [f"# {wf['name']} — stages", "", "<!-- Generated by scripts/package/render_roles.py from workflow.yaml. -->", "",
             wf["summary"], "", f"**Trigger:** {wf['trigger']}", "",
             "| Stage | Agent | Skills | Depends on | Parallel group | Gate | Reviewer | Human approval | Risk | Outputs |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for s in wf["stages"]:
        lines.append("| `{id}` | `{agent}` | {skills} | {dep} | {pg} | {gate} | {rev} | {ha} | {risk} | {out} |".format(
            id=s["id"], agent=s["agent"], skills=", ".join(s.get("skills", [])), dep=", ".join(s.get("depends_on", [])) or "—",
            pg=s.get("parallel_group", "—"), gate=s.get("gate", "—"), rev=s.get("review", "—"),
            ha="yes" if s.get("human_approval") else "—", risk=s.get("risk", "—"),
            out="<br>".join(f"`{o}`" for o in s.get("outputs", []))))
    lines += ["", "## Final deliverables", ""] + [f"- `{d}`" for d in wf.get("final_deliverables", [])]
    rp = wf.get("retry_policy", {})
    if rp:
        lines += ["", f"Review loops per stage: {rp.get('max_review_loops')} · on exhaustion: {rp.get('on_exhausted')}"]
    return "\n".join(lines) + "\n"


def render_agents_directory(agents: dict[str, dict]) -> str:
    lines = ["# Agents directory", "", HEADER, "",
             "Every agent with its tier, department, skills, tools, write scope and autonomy. Source of truth: `agents/**/*.yaml`. "
             "Platform renderings: `adapters/kiro/agents/`, `adapters/claude-code/agents/`, `adapters/codex/AGENTS.md`.", ""]
    for tier, title in (("orchestrator", "Orchestrator"), ("executive", "Executives (advise only)"),
                        ("department-lead", "Department leads (propose, may delegate within department)"),
                        ("specialist", "Specialists (propose)"), ("reviewer", "Independent reviewers (read-only)")):
        rows = [a for a in agents.values() if a.get("tier") == tier]
        lines += [f"## {title} ({len(rows)})", "",
                  "| Agent | Department | Title | Skills | Tools | Write scope | Reviews gates |", "|---|---|---|---|---|---|---|"]
        for a in sorted(rows, key=lambda x: x["id"]):
            lines.append("| `{id}` | {dep} | {title} | {skills} | {tools} | {ws} | {rev} |".format(
                id=a["id"], dep=a["department"], title=a["title"], skills=", ".join(a.get("skills", [])),
                tools=", ".join(a.get("tools", [])), ws="<br>".join(f"`{w}`" for w in a.get("write_scope", [])) or "—",
                rev=", ".join(a.get("reviews", [])) or "—"))
        lines.append("")
    lines += [f"{len(agents)} agents."]
    return "\n".join(lines) + "\n"


def main() -> None:
    report = Report("render")
    deps = load_departments(report)
    agents = load_all_agents(report)
    (ROOT / "docs" / "agents").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "agents" / "README.md").write_text(render_agents_directory(agents), encoding="utf-8", newline="\n")
    OUT.mkdir(parents=True, exist_ok=True)
    for did, data in deps.items():
        (OUT / f"{did}.md").write_text(render_department(data), encoding="utf-8", newline="\n")
    (OUT / "README.md").write_text(render_index(deps), encoding="utf-8", newline="\n")
    n = 0
    for wf_path in sorted((ROOT / "workflows").glob("*/workflow.yaml")):
        wf = load_yaml(wf_path, report)
        if isinstance(wf, dict):
            (wf_path.parent / "STAGES.md").write_text(render_stages(wf), encoding="utf-8", newline="\n")
            n += 1
    print(f"Rendered {len(deps)} department docs to docs/organization/ and {n} workflow stage tables")
    if report.errors:
        for e in report.errors:
            print("ERROR", e)
        sys.exit(1)


if __name__ == "__main__":
    main()
