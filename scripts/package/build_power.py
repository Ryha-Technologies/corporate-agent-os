#!/usr/bin/env python3
"""Build the Kiro Power at powers/kiro/corporate-agent-os from canonical skills and the manifest template.

The power follows Agent Plugins 1.0.0 as documented by Kiro (kiro.dev/docs/powers/create, 2026-11-18):
plugin.json + skills/<name>/SKILL.md (+ references/, scripts/, assets/). Nothing else is added, because Kiro
documents no other directories. Steering, hooks and custom agents ship in adapters/kiro and are installed into
.kiro/ by scripts/install/install.py.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
POWER_DIR = ROOT / "powers" / "kiro" / "corporate-agent-os"
MANIFEST_TEMPLATE = ROOT / "adapters" / "kiro" / "plugin.template.json"
SKILLS = ROOT / "skills"


def build(power_dir: Path = POWER_DIR) -> Path:
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    manifest = json.loads(MANIFEST_TEMPLATE.read_text(encoding="utf-8"))
    manifest["version"] = version
    if power_dir.exists():
        shutil.rmtree(power_dir)
    (power_dir / "skills").mkdir(parents=True)
    (power_dir / "plugin.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    count = 0
    for skill in sorted(SKILLS.iterdir()):
        if skill.is_dir() and (skill / "SKILL.md").exists():
            shutil.copytree(skill, power_dir / "skills" / skill.name,
                            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
            count += 1
    shutil.copy2(ROOT / "LICENSE", power_dir / "LICENSE")
    readme = f"""# Corporate Agent OS — Kiro Power

Version {version}. Generated by `scripts/package/build_power.py`; do not edit here, edit `skills/` at the repository root and rebuild.

This power packages the {count} canonical Corporate Agent OS skills in the Agent Plugins 1.0.0 format that Kiro Powers use. Install it in Kiro with **Powers → Add Custom Power → Import power from a folder** (this directory) or **Import power from GitHub** (the repository URL plus this subfolder path). Kiro activates it when your request matches the keywords in `plugin.json`, or invoke a skill directly with `/skill-name`.

Created and maintained by Velluraju C (https://github.com/velluraju). MIT licence.

The power contains skills only. The orchestration agents, steering and hooks for Kiro are installed separately into your project's `.kiro/` directory by `python scripts/install/install.py --target kiro` because Kiro documents no power component for those.
"""
    (power_dir / "README.md").write_text(readme, encoding="utf-8", newline="\n")
    print(f"Built Kiro Power v{version} with {count} skills at {power_dir}")
    return power_dir


if __name__ == "__main__":
    build(Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else POWER_DIR)
